import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
export const root = fileURLToPath(new URL('../', import.meta.url));
export function assemble() {
  const parts = Array.from({length:8}, (_,i) => readFileSync(`${root}chapter-${String(i+1).padStart(2,'0')}.ink`, 'utf8'));
  const ending = parts[0].lastIndexOf('-> END');
  if (ending < 0) throw Error('Chapter one standalone ending missing');
  parts[0] = parts[0].slice(0, ending) + '-> chapter_02_start' + parts[0].slice(ending+6);
  return '// Generated by tools/build.mjs. Edit chapter sources, then rebuild.\n' + parts.join('\n');
}
const source = assemble();
if (process.argv.includes('--check')) {
  if (readFileSync(`${root}story.ink`, 'utf8') !== source) throw Error('story.ink is out of date');
} else writeFileSync(`${root}story.ink`, source);
