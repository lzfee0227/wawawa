import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

test('V09–V11 readonly React Flow maps show real content on desktop and narrow screens', async ({ page, request }) => {
  const source = readFileSync('content/stories/erha-youfu/story.ink', 'utf8');
  const metadata = JSON.parse(readFileSync('content/stories/erha-youfu/authoring.json', 'utf8'));
  const response = await request.post('/api/stories', { data: { title: `图形验证 ${Date.now()}`, source, ...metadata } });
  expect(response.ok()).toBeTruthy();
  const draft = await response.json();
  const writes: string[] = [];
  page.on('request', req => { if (req.method() !== 'GET' && !req.url().endsWith('/api/analyze')) writes.push(req.url()); });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/');
  await page.getByRole('button', { name: new RegExp(draft.title) }).click();
  await page.getByRole('tab', { name: '人物与剧情图' }).click();
  await expect(page.locator('.react-flow__node')).toHaveCount(8);
  await expect(page.locator('.react-flow__edge')).toHaveCount(7);
  const node = page.locator('[data-testid="rf__node-ma_er_fu"]');
  await node.focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('complementary', { name: '节点详情' })).toContainText('马二福');
  await page.getByLabel('查找人物节点').fill('李二哈');
  await page.getByRole('button', { name: '李二哈', exact: true }).click();
  await expect(page.getByRole('complementary', { name: '节点详情' })).toContainText('承福血脉');
  await page.getByRole('button', { name: '适配画布', exact: true }).first().click();
  await page.getByLabel('查找人物节点').fill('');
  await page.getByRole('region', { name: '人物画布' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/relations-desktop.png', fullPage: true });
  await page.getByRole('button', { name: '剧情分支图', exact: true }).click();
  await expect(page.getByLabel('查看范围')).toBeVisible();
  await page.getByLabel('查看范围').selectOption('scene:arrival');
  await expect(page.locator('.react-flow__edge').first()).toBeVisible();
  await page.getByRole('region', { name: '剧情画布' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/plot-desktop.png', fullPage: true });
  const viewport = page.locator('.react-flow__viewport');
  const transform = await viewport.getAttribute('style');
  await page.getByRole('button', { name: '放大', exact: true }).click();
  await expect(viewport).not.toHaveAttribute('style', transform!);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '适配画布', exact: true }).first().click();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('region', { name: '剧情画布' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/plot-narrow.png', fullPage: true });
  await page.getByRole('button', { name: '人物关系图', exact: true }).click();
  await page.getByRole('button', { name: '适配画布', exact: true }).first().click();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/relations-narrow.png', fullPage: true });
  expect(errors).toEqual([]);
  expect(writes).toEqual([]);
  const saved = await (await request.get(`/api/stories/${draft.id}`)).json();
  expect(saved.revision).toBe(draft.revision);
  expect(saved.source).toBe(source);
  expect(saved.relations).toEqual(metadata.relations);
});
